#ifndef INFERENCEOS_RESULT_H
#define INFERENCEOS_RESULT_H

#include <inferenceos/base.h>

typedef enum inferenceos_result {
    INFERENCEOS_RESULT_OK = 0,
    INFERENCEOS_RESULT_INVALID_ARGUMENT = 1,
    INFERENCEOS_RESULT_OVERFLOW = 2,
    INFERENCEOS_RESULT_OUT_OF_RANGE = 3,
    INFERENCEOS_RESULT_UNSUPPORTED = 4,
    INFERENCEOS_RESULT_NOT_FOUND = 5,
    INFERENCEOS_RESULT_ALREADY_EXISTS = 6,
    INFERENCEOS_RESULT_NO_SPACE = 7,
    INFERENCEOS_RESULT_BUSY = 8,
    INFERENCEOS_RESULT_READ_ONLY = 9,
    INFERENCEOS_RESULT_NOT_READY = 10,
    INFERENCEOS_RESULT_IO_ERROR = 11,
    INFERENCEOS_RESULT_TIMEOUT = 12,
    INFERENCEOS_RESULT_CORRUPT = 13,
    INFERENCEOS_RESULT_INCONSISTENT = 14,
    INFERENCEOS_RESULT_NOT_MOUNTED = 15,
    INFERENCEOS_RESULT_NOT_EMPTY = 16,
    INFERENCEOS_RESULT_END_OF_INPUT = 17,
    INFERENCEOS_RESULT_INTERNAL_ERROR = 18
} inferenceos_result;

static inline bool inferenceos_result_is_success(inferenceos_result result)
{
    return result == INFERENCEOS_RESULT_OK;
}

#endif
